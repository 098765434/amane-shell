//! The token functions' source: `tokens::sys`, `tokens::bar`, … as Rust
//! text, from a parsed Penpot export. `build.rs` includes this file and
//! writes what [`generate`] returns into `OUT_DIR`; the kit compiles it
//! only for its tests.
//!
//! One function per `sys.*` and component token, nested by the token's
//! name, returning its current value with the Rust type of its Penpot
//! `$type`. There is deliberately no `ref` module: code never reads
//! primitives.

use std::collections::BTreeMap;
use std::fmt::Write;

use super::envelope::{Library, TokenType};

/// The generated source for `library`: the nested token modules and the
/// `GENERATED` table the contract tests read. An `Err` names the tokens
/// that can't both be generated.
pub fn generate(library: &Library) -> Result<String, String> {
    let tokens = token_types(library)?;

    let mut tree = Node::default();
    for (name, ty) in &tokens {
        let mut node = &mut tree;
        let parts: Vec<&str> = name.split('.').collect();
        let Some((leaf, groups)) = parts.split_last() else {
            continue;
        };
        for part in groups {
            node = node.children.entry((*part).to_string()).or_default();
        }
        node.leaves.insert((*leaf).to_string(), (name.clone(), *ty));
    }

    let mut out = String::from("// @generated by build.rs from design-tokens/tokens.json\n\n");
    for (name, child) in &tree.children {
        emit_module(&mut out, name, name, child, 0)?;
    }
    out.push_str("\n/// Every generated token, its Penpot type and its function's path, for\n");
    out.push_str("/// the contract tests.\n");
    out.push_str("pub const GENERATED: &[(&str, &str, &str)] = &[\n");
    for (name, ty) in &tokens {
        let path: Vec<String> = name.split('.').map(ident).collect();
        let _ = writeln!(
            out,
            "    ({name:?}, {:?}, {:?}),",
            ty.name(),
            path.join("::")
        );
    }
    out.push_str("];\n");
    Ok(out)
}

/// Every name the code may read, with its Penpot type. A name with one
/// type in one set and another type in another is an error.
fn token_types(library: &Library) -> Result<BTreeMap<String, TokenType>, String> {
    let mut tokens: BTreeMap<String, TokenType> = BTreeMap::new();
    for set in &library.sets {
        for token in set.tokens.iter().filter(|t| !t.name.starts_with("ref.")) {
            match tokens.get(&token.name) {
                Some(other) if *other != token.ty => {
                    return Err(format!(
                        "{} is a {} token in one set and a {} token in set {}",
                        token.name,
                        other.name(),
                        token.ty.name(),
                        set.name
                    ));
                }
                _ => {
                    tokens.insert(token.name.clone(), token.ty);
                }
            }
        }
    }
    Ok(tokens)
}

#[derive(Default)]
struct Node {
    children: BTreeMap<String, Node>,
    /// segment → (full token name, Penpot type)
    leaves: BTreeMap<String, (String, TokenType)>,
}

/// The Rust return type and the `read` function for a Penpot type.
fn reader(ty: TokenType) -> (&'static str, &'static str) {
    use TokenType::*;

    match ty {
        Color => ("amane::Color", "color"),
        FontSizes => ("f32", "font_size"),
        Dimension | Sizing | Spacing | BorderRadius | BorderWidth | LetterSpacing | Number
        | Rotation | Opacity => ("f32", "number"),
        FontFamilies => ("&'static str", "font_family"),
        FontWeights => ("u16", "font_weight"),
        Typography => ("TextStyle", "text_style"),
        Shadow => ("Vec<Shadow>", "shadow"),
        Boolean => ("bool", "boolean"),
        String | Other => ("String", "string"),
        TextCase => ("TextCase", "text_case"),
        TextDecoration => ("TextDecoration", "text_decoration"),
    }
}

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false",
    "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
    "ref", "return", "static", "struct", "trait", "true", "try", "type", "unsafe", "use", "where",
    "while", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof",
    "unsized", "virtual", "yield",
];

/// A token name segment as a Rust identifier: hyphens become underscores, a
/// leading digit gets an underscore (`2xs` → `_2xs`), keywords are raw
/// (`type` → `r#type`), and the path keywords that can't be raw get a
/// trailing underscore (`self` → `self_`).
fn ident(segment: &str) -> String {
    let mut id = segment.replace('-', "_");
    if id.starts_with(|c: char| c.is_ascii_digit()) {
        id.insert(0, '_');
    }
    if ["self", "super", "crate", "Self"].contains(&id.as_str()) {
        id.push('_');
    } else if KEYWORDS.contains(&id.as_str()) {
        id.insert_str(0, "r#");
    }
    id
}

/// Writes module `name` (the token group `path`) and everything under it.
/// Writing to a `String` can't fail, so `writeln!`'s result is dropped.
fn emit_module(
    out: &mut String,
    name: &str,
    path: &str,
    node: &Node,
    depth: usize,
) -> Result<(), String> {
    let pad = "    ".repeat(depth);
    let _ = writeln!(out, "{pad}/// The `{path}.*` tokens.");
    let _ = writeln!(out, "{pad}pub mod {} {{", ident(name));
    let _ = writeln!(out, "{pad}    #[allow(unused_imports)]");
    let _ = writeln!(
        out,
        "{pad}    use crate::tokens::{{Shadow, TextCase, TextDecoration, TextStyle, read}};"
    );

    let mut seen = BTreeMap::new();
    for (segment, (full, ty)) in &node.leaves {
        let id = ident(segment);
        if let Some(other) = seen.insert(id.clone(), full.clone()) {
            return Err(format!(
                "{other} and {full} map to the same Rust name `{id}`"
            ));
        }
        let (ret, read) = reader(*ty);
        let _ = writeln!(out, "\n{pad}    /// `{full}` ({})", ty.name());
        let _ = writeln!(out, "{pad}    pub fn {id}() -> {ret} {{");
        let _ = writeln!(out, "{pad}        read::{read}({full:?})");
        let _ = writeln!(out, "{pad}    }}");
    }

    for (child, sub) in &node.children {
        out.push('\n');
        emit_module(out, child, &format!("{path}.{child}"), sub, depth + 1)?;
    }
    let _ = writeln!(out, "{pad}}}");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn library(json: &str) -> Library {
        Library::parse(json).expect("a valid export")
    }

    #[test]
    fn segments_become_rust_identifiers() {
        assert_eq!(ident("on-surface"), "on_surface");
        assert_eq!(ident("2xs"), "_2xs");
        assert_eq!(ident("type"), "r#type");
        assert_eq!(ident("self"), "self_");
        assert_eq!(ident("Self"), "Self_");
        assert_eq!(ident("super"), "super_");
        assert_eq!(ident("plain"), "plain");
    }

    #[test]
    fn two_segments_with_one_rust_name_are_refused() {
        let lib = library(
            r#"{ "s": { "sys": { "$type": "number",
                "a-b": { "$value": "1" }, "a_b": { "$value": "2" } } } }"#,
        );
        let err = generate(&lib).expect_err("a-b and a_b clash");
        assert!(err.contains("`a_b`"), "{err}");
    }

    #[test]
    fn a_name_with_two_types_is_refused() {
        let lib = library(
            r##"{ "one": { "sys": { "x": { "$type": "number", "$value": "1" } } },
                 "two": { "sys": { "x": { "$type": "color", "$value": "#fff" } } } }"##,
        );
        let err = generate(&lib).expect_err("x is a number and a colour");
        assert!(err.contains("sys.x"), "{err}");
    }

    #[test]
    fn a_small_tree_generates_this_source() {
        let lib = library(
            r##"{ "s": {
                "ref": { "gray": { "$type": "color", "$value": "#888" } },
                "sys": { "space": { "$type": "spacing", "2xs": { "$value": "2" } },
                         "type": { "$type": "boolean", "$value": "true" } } } }"##,
        );
        let expected = r#"// @generated by build.rs from design-tokens/tokens.json

/// The `sys.*` tokens.
pub mod sys {
    #[allow(unused_imports)]
    use crate::tokens::{Shadow, TextCase, TextDecoration, TextStyle, read};

    /// `sys.type` (boolean)
    pub fn r#type() -> bool {
        read::boolean("sys.type")
    }

    /// The `sys.space.*` tokens.
    pub mod space {
        #[allow(unused_imports)]
        use crate::tokens::{Shadow, TextCase, TextDecoration, TextStyle, read};

        /// `sys.space.2xs` (spacing)
        pub fn _2xs() -> f32 {
            read::number("sys.space.2xs")
        }
    }
}

/// Every generated token, its Penpot type and its function's path, for
/// the contract tests.
pub const GENERATED: &[(&str, &str, &str)] = &[
    ("sys.space.2xs", "spacing", "sys::space::_2xs"),
    ("sys.type", "boolean", "sys::r#type"),
];
"#;
        assert_eq!(generate(&lib).expect("generates"), expected);
    }
}
