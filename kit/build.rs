//! Generates `tokens::sys`, `tokens::bar`, `tokens::menu`, … from
//! `design-tokens/tokens.json`, with the generator in
//! `src/tokens/codegen.rs` (tested there). A token renamed in Penpot then
//! fails the build at the line that reads it. Also embeds the Shader Lab's
//! effects and saved looks.
//!
//! The export is read by the kit's own parser (`src/tokens/envelope.rs`),
//! so the build refuses exactly what the kit refuses at run time.

use std::fmt::Write;
use std::{env, fs, path::Path};

#[allow(dead_code)]
#[path = "src/tokens/codegen.rs"]
mod codegen;
#[allow(dead_code)]
#[path = "src/tokens/envelope.rs"]
mod envelope;
#[allow(dead_code)]
#[path = "src/tokens/error.rs"]
mod error;

use envelope::Library;

const SOURCE: &str = "../design-tokens/tokens.json";

fn main() {
    println!("cargo::rerun-if-changed={SOURCE}");
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=src/tokens/codegen.rs");
    println!("cargo::rerun-if-changed=src/tokens/envelope.rs");
    println!("cargo::rerun-if-changed=src/tokens/error.rs");

    let json = fs::read_to_string(SOURCE).unwrap_or_else(|e| fail(&format!("{SOURCE}: {e}")));
    let library = Library::parse(&json).unwrap_or_else(|e| fail(&format!("{SOURCE}: {e}")));

    let out = codegen::generate(&library).unwrap_or_else(|e| fail(&e));

    let dest = Path::new(&env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("tokens.rs");
    fs::write(dest, out).expect("write generated tokens");

    lab_registry();
}

/// The Shader Lab's effect folders and saved configs, every file embedded,
/// so `kit::lab::look` works in a binary that ships alone.
const LAB: &str = "../apps/shader-lab";

fn lab_registry() {
    let mut files = Vec::new();

    for folder in ["effects", "configs"] {
        let dir = Path::new(LAB).join(folder);

        println!("cargo::rerun-if-changed={}", dir.display());

        collect(&dir, folder, &mut files);
    }

    files.sort();

    let mut out = String::from("// generated by build.rs from apps/shader-lab\n");
    out.push_str("pub static FILES: &[(&str, &str)] = &[\n");

    let root =
        Path::new(&env::var("CARGO_MANIFEST_DIR").expect("cargo sets the manifest dir")).join(LAB);

    for name in &files {
        let path = root.join(name);

        // include_str! follows links, like glass.wgsl's into the kit
        writeln!(
            out,
            "    ({name:?}, include_str!({:?})),",
            path.display().to_string()
        )
        .expect("write to a string");
    }

    out.push_str("];\n");

    let dest = Path::new(&env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("lab_files.rs");
    fs::write(dest, out).expect("write the lab registry");
}

/// Every file under `dir`, named from `prefix` with forward slashes.
fn collect(dir: &Path, prefix: &str, files: &mut Vec<String>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };

    for entry in entries.flatten() {
        let path = entry.path();
        let name = format!("{prefix}/{}", entry.file_name().to_string_lossy());

        // metadata follows links, so a linked shader counts as a file
        match fs::metadata(&path) {
            Ok(meta) if meta.is_dir() => collect(&path, &name, files),
            Ok(meta) if meta.is_file() => files.push(name),
            _ => {}
        }
    }
}

fn fail(message: &str) -> ! {
    panic!("design tokens: {message}")
}
