//! Embeds the lab's effect folders and saved configs: `FILES` in
//! `OUT_DIR/lab_files.rs`, every file by its path here
//! (`effects/chrome/chrome.wgsl`, `configs/dock-glass.json`). The lab hands
//! it to `amane_kit::lab::register`, so its looks work in a binary that
//! ships alone.

use std::fmt::Write;
use std::{env, fs, path::Path};

fn main() {
    lab_registry();
}

fn lab_registry() {
    let mut files = Vec::new();

    for folder in ["effects", "configs"] {
        let dir = Path::new(folder);

        println!("cargo::rerun-if-changed={}", dir.display());

        collect(dir, folder, &mut files);
    }

    files.sort();

    let mut out = String::from("// generated by build.rs from apps/shader-lab\n");
    out.push_str("pub static FILES: &[(&str, &str)] = &[\n");

    let root = std::path::PathBuf::from(
        env::var("CARGO_MANIFEST_DIR").expect("cargo sets the manifest dir"),
    );

    for name in &files {
        let path = root.join(name);

        // include_str! follows links, like glass.wgsl's into the kit
        writeln!(
            out,
            "    ({name:?}, include_str!({:?})),",
            path.display().to_string()
        )
        .expect("write to a string");
    }

    out.push_str("];\n");

    let dest = Path::new(&env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("lab_files.rs");
    fs::write(dest, out).expect("write the lab registry");
}

/// Every file under `dir`, named from `prefix` with forward slashes.
fn collect(dir: &Path, prefix: &str, files: &mut Vec<String>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };

    for entry in entries.flatten() {
        let path = entry.path();
        let name = format!("{prefix}/{}", entry.file_name().to_string_lossy());

        // metadata follows links, so a linked shader counts as a file
        match fs::metadata(&path) {
            Ok(meta) if meta.is_dir() => collect(&path, &name, files),
            Ok(meta) if meta.is_file() => files.push(name),
            _ => {}
        }
    }
}
