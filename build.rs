//! Generates `tokens::sys`, `tokens::bar`, `tokens::menu`, … from
//! `design-tokens/tokens.json`: one function per `sys.*` and component token,
//! nested by the token's name, returning its current value with the Rust
//! type of its Penpot `$type`. A token renamed in Penpot then fails the
//! build at the line that reads it. There is deliberately no `ref` module:
//! code never reads primitives.

use std::collections::BTreeMap;
use std::fmt::Write;
use std::{env, fs, path::Path};

use serde_json::{Map, Value};

const SOURCE: &str = "design-tokens/tokens.json";

fn main() {
    println!("cargo::rerun-if-changed={SOURCE}");
    println!("cargo::rerun-if-changed=build.rs");

    let json = fs::read_to_string(SOURCE).unwrap_or_else(|e| fail(&format!("{SOURCE}: {e}")));
    let root: Value =
        serde_json::from_str(&json).unwrap_or_else(|e| fail(&format!("{SOURCE}: {e}")));
    let root = root
        .as_object()
        .unwrap_or_else(|| fail(&format!("{SOURCE} is not a JSON object")));

    // every name the code may read, with its Penpot type
    let mut tokens: BTreeMap<String, String> = BTreeMap::new();
    for (set, tree) in root.iter().filter(|(k, _)| !k.starts_with('$')) {
        let Some(tree) = tree.as_object() else {
            fail(&format!("set {set} is not an object"));
        };
        let mut found = Vec::new();
        flatten(tree, "", None, &mut found);
        for (name, ty) in found {
            if name.starts_with("ref.") {
                continue;
            }
            match tokens.get(&name) {
                Some(other) if *other != ty => fail(&format!(
                    "{name} is a {other} token in one set and a {ty} token in set {set}"
                )),
                _ => {
                    tokens.insert(name, ty);
                }
            }
        }
    }

    let mut tree = Node::default();
    for (name, ty) in &tokens {
        let mut node = &mut tree;
        let parts: Vec<&str> = name.split('.').collect();
        for part in &parts[..parts.len() - 1] {
            node = node.children.entry(part.to_string()).or_default();
        }
        node.leaves.insert(
            parts[parts.len() - 1].to_string(),
            (name.clone(), ty.clone()),
        );
    }

    let mut out = String::from("// @generated by build.rs from design-tokens/tokens.json\n\n");
    for (name, child) in &tree.children {
        emit_module(&mut out, name, child, 0);
    }
    out.push_str("\n/// Every generated token and its Penpot type, for the contract tests.\n");
    out.push_str("pub const GENERATED: &[(&str, &str)] = &[\n");
    for (name, ty) in &tokens {
        let _ = writeln!(out, "    ({name:?}, {ty:?}),");
    }
    out.push_str("];\n");

    let dest = Path::new(&env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("tokens.rs");
    fs::write(dest, out).expect("write generated tokens");
}

fn fail(message: &str) -> ! {
    panic!("design tokens: {message}")
}

#[derive(Default)]
struct Node {
    children: BTreeMap<String, Node>,
    /// segment → (full token name, Penpot type)
    leaves: BTreeMap<String, (String, String)>,
}

fn flatten(
    node: &Map<String, Value>,
    path: &str,
    inherited: Option<&str>,
    out: &mut Vec<(String, String)>,
) {
    let ty = node.get("$type").and_then(Value::as_str).or(inherited);

    if node.contains_key("$value") {
        let ty = ty.unwrap_or_else(|| fail(&format!("{path} has no $type")));
        out.push((path.to_string(), ty.to_string()));
        return;
    }

    for (key, child) in node.iter().filter(|(k, _)| !k.starts_with('$')) {
        let child_path = if path.is_empty() {
            key.clone()
        } else {
            format!("{path}.{key}")
        };
        if let Some(child) = child.as_object() {
            flatten(child, &child_path, ty, out);
        }
    }
}

/// The Rust return type and the `read` function for a Penpot type.
fn reader(ty: &str, name: &str) -> (&'static str, &'static str) {
    match ty {
        "color" => ("amane::Color", "color"),
        "fontSizes" | "fontSize" => ("f32", "font_size"),
        "dimension" | "sizing" | "spacing" | "borderRadius" | "borderWidth" | "letterSpacing"
        | "number" | "rotation" | "opacity" => ("f32", "number"),
        "fontFamilies" | "fontFamily" => ("&'static str", "font_family"),
        "fontWeights" | "fontWeight" => ("u16", "font_weight"),
        "typography" => ("TextStyle", "text_style"),
        "shadow" | "boxShadow" => ("Vec<Shadow>", "shadow"),
        "boolean" => ("bool", "boolean"),
        "string" | "other" => ("String", "string"),
        "textCase" => ("TextCase", "text_case"),
        "textDecoration" => ("TextDecoration", "text_decoration"),
        other => fail(&format!("{name} has unknown $type {other}")),
    }
}

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false",
    "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
    "ref", "return", "static", "struct", "trait", "true", "try", "type", "unsafe", "use", "where",
    "while", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof",
    "unsized", "virtual", "yield",
];

/// A token name segment as a Rust identifier: hyphens become underscores, a
/// leading digit gets an underscore (`2xs` → `_2xs`), keywords are raw
/// (`type` → `r#type`).
fn ident(segment: &str) -> String {
    let mut id = segment.replace('-', "_");
    if id.starts_with(|c: char| c.is_ascii_digit()) {
        id.insert(0, '_');
    }
    if ["self", "super", "crate", "Self"].contains(&id.as_str()) {
        id.push('_');
    } else if KEYWORDS.contains(&id.as_str()) {
        id.insert_str(0, "r#");
    }
    id
}

fn emit_module(out: &mut String, name: &str, node: &Node, depth: usize) {
    let pad = "    ".repeat(depth);
    let _ = writeln!(out, "{pad}pub mod {} {{", ident(name));
    let _ = writeln!(out, "{pad}    #[allow(unused_imports)]");
    let _ = writeln!(
        out,
        "{pad}    use crate::tokens::{{Shadow, TextCase, TextDecoration, TextStyle, read}};"
    );

    let mut seen = BTreeMap::new();
    for (segment, (full, ty)) in &node.leaves {
        let id = ident(segment);
        if let Some(other) = seen.insert(id.clone(), full.clone()) {
            fail(&format!(
                "{full} and {other} map to the same Rust name `{id}`"
            ));
        }
        let (ret, read) = reader(ty, full);
        let _ = writeln!(out, "\n{pad}    /// `{full}` ({ty})");
        let _ = writeln!(out, "{pad}    pub fn {id}() -> {ret} {{");
        let _ = writeln!(out, "{pad}        read::{read}({full:?})");
        let _ = writeln!(out, "{pad}    }}");
    }

    for (child, sub) in &node.children {
        out.push('\n');
        emit_module(out, child, sub, depth + 1);
    }
    let _ = writeln!(out, "{pad}}}");
}
