//! niri layer rules from tokens: the compositor's blur corners come from the
//! same radius role the shell draws its cards with, so they can't drift.
//! `amane-shell layer-rules` prints the file; `niri-layer-rule.kdl` is its
//! committed output, checked by a golden test.

use std::fmt::Write;

use crate::components::context_menu::NAMESPACE_ANCHOR;
use crate::components::taskbar::{POWER_NS, WIFI_NS};
use crate::theme::{Density, Mode};
use crate::tokens::{Key, sys, with_key};

pub struct LayerRule {
    pub namespace: &'static str,
    pub comment: &'static str,
    /// Corner radius of the surface's own blur, if the surface is blurred.
    pub radius: Option<f32>,
    pub blur: bool,
    /// Corner radius and blur for the surface's xdg-popups.
    pub popups: Option<(f32, bool)>,
}

/// One rule per frosted surface. The bar has none: it is deliberately not
/// blurred.
pub fn rules() -> Vec<LayerRule> {
    // radii don't vary with mode or density (a contract test checks it)
    let popover = with_key(
        Key::new(Mode::Dark, Density::Comfortable),
        sys::radius::popover,
    );

    vec![
        LayerRule {
            namespace: NAMESPACE_ANCHOR,
            comment: "Context menu. The anchor is an invisible 1×1 layer-surface; the visible\n\
                      cards (menu + nested submenus) are xdg-popups of it, so the `popups {}`\n\
                      block styles every level uniformly. Namespaces: the anchor is\n\
                      `amane.context-menu-anchor`; each depth level is `amane.context-menu.0`..`7`.",
            radius: None,
            blur: false,
            popups: Some((popover, true)),
        },
        LayerRule {
            namespace: WIFI_NS,
            comment: "Wi-Fi panel: a rounded frosted card anchored bottom-right, toggled by the\n\
                      taskbar's network indicator.",
            radius: Some(popover),
            blur: true,
            popups: None,
        },
        LayerRule {
            namespace: POWER_NS,
            comment: "Power panel: the same frosted card, toggled by the taskbar's battery\n\
                      indicator.",
            radius: Some(popover),
            blur: true,
            popups: None,
        },
    ]
}

const HEADER: &str = "\
// GENERATED by `cargo run -q -- layer-rules > niri-layer-rule.kdl` from the
// design tokens (radii: sys.radius.popover) — do not edit by hand.
//
// The amane shell's niri layer-rules (compositor-side blur / rounding on its
// surfaces). Each rule matches an anchored regex on a layer-surface namespace
// that a component sets via LayerWindow::namespace(...).
//
// Don't hand-copy these into the niri config. gen-layer-rules.sh injects
// everything below the sentinel into the config between its
// `>>> amane layer-rules` / `<<<` markers (see docs/layer-rules.md); then:
//
//     niri validate -c ~/.config/niri/config.kdl
//     niri msg action load-config-file
//
// Verify the surfaces are up:  niri msg layers | grep amane

//<<<GENERATED-RULES-BELOW>>>  (gen-layer-rules.sh injects everything past this line)

// Taskbar: a full-width bottom bar. It is deliberately NOT blurred — only the
// floating surfaces (menus and the Wi-Fi and power cards) are frosted.
// (No layer-rule for `amane.taskbar` on purpose.)
";

/// The whole `niri-layer-rule.kdl`.
pub fn render(rules: &[LayerRule]) -> String {
    let mut out = String::from(HEADER);

    for rule in rules {
        out.push('\n');
        for line in rule.comment.lines() {
            let _ = writeln!(out, "// {}", line.trim_start());
        }
        out.push_str("layer-rule {\n");
        let _ = writeln!(
            out,
            "    match namespace=\"{}\"",
            kdl_string(&anchored(rule.namespace))
        );
        if let Some(radius) = rule.radius {
            let _ = writeln!(out, "    geometry-corner-radius {radius}");
        }
        // niri gives a layer-surface's blur xray by default, which shows only
        // the wallpaper; these cards float over windows, so they blur what's
        // below (popups already default to that)
        if rule.blur {
            out.push_str("    background-effect {\n        blur true\n        xray false\n    }\n");
        }
        if let Some((radius, blur)) = rule.popups {
            out.push_str("\n    popups {\n");
            let _ = writeln!(out, "        geometry-corner-radius {radius}");
            if blur {
                out.push_str("        background-effect {\n            blur true\n        }\n");
            }
            out.push_str("    }\n");
        }
        out.push_str("}\n");
    }

    out
}

/// `^…$` with regex metacharacters escaped.
fn anchored(namespace: &str) -> String {
    let mut out = String::from("^");
    for c in namespace.chars() {
        if r"\.^$|?*+()[]{}".contains(c) {
            out.push('\\');
        }
        out.push(c);
    }
    out.push('$');
    out
}

fn kdl_string(s: &str) -> String {
    s.replace('\\', r"\\").replace('"', "\\\"")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn committed_kdl_matches_the_tokens() {
        let committed = include_str!("../../niri-layer-rule.kdl");
        assert!(
            committed == render(&rules()),
            "niri-layer-rule.kdl is out of date — run: \
             cargo run -q -- layer-rules > niri-layer-rule.kdl"
        );
    }

    #[test]
    fn namespaces_are_escaped() {
        assert_eq!(
            kdl_string(&anchored("amane.taskbar.wifi")),
            r"^amane\\.taskbar\\.wifi$"
        );
        assert_eq!(anchored("a+b(c)"), r"^a\+b\(c\)$");
    }
}
